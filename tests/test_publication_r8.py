"""The publication scanner blocks attribution footers without naming any tool."""

import re
import runpy
from pathlib import Path

MODULE = runpy.run_path(str(Path(__file__).resolve().parents[1] / "scripts" / "prepare_public.py"))


def test_attribution_footer_pattern_matches_generic_footers():
    pattern = MODULE["ATTRIBUTION_LINK"]
    assert re.search(pattern, b"Generated with [Some Tool](https://example.com/tool)\n")
    assert re.search(pattern, b"notes\n  generated by [Another](http://example.org/x)\n")
    assert not re.search(pattern, b"Generated by the cohort pipeline from public data.\n")


def test_extra_patterns_come_only_from_the_environment(monkeypatch):
    monkeypatch.setenv("PREPARE_PUBLIC_EXTRA_PATTERNS", "alpha\n\n(?i)beta\n")
    assert MODULE["extra_patterns"]() == [b"alpha", b"(?i)beta"]
    monkeypatch.delenv("PREPARE_PUBLIC_EXTRA_PATTERNS")
    assert MODULE["extra_patterns"]() == []
