"""Prepare a separate one-commit public snapshot, preserving the original history."""

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import tempfile
from pathlib import Path


def git(root, *args, **kwargs):
    return subprocess.check_output(["git", "-C", str(root), *args], **kwargs)


def source_identity(root):
    """Read the owner's release identity from the approved source commit metadata."""
    fields = git(root, "show", "-s", "--format=%an%x00%ae%x00%cn%x00%ce", "HEAD")
    author_name, author_email, committer_name, committer_email = fields.decode().strip().split("\0")
    if (author_name, author_email) != (committer_name, committer_email):
        raise ValueError("Source author and committer must share the owner's identity")
    return author_name, author_email


def scan_history(root, identity):
    """Scan all reachable commit metadata and blobs of this release artifact."""
    forbidden = [
        rb"/Users/[a-zA-Z0-9]",
        rb"\xe2\x80\x94",
        rb"AKIA[0-9A-Z]{16}",
        rb"gh[pousr]_[A-Za-z0-9]{30,}",
        rb"(?m)^-----BEGIN [A-Z ]*PRIVATE KEY-----$",
        rb"(?m)^Co-authored-by:\s+.+ <.+>",
        rb"(?i)generated by (?:claude|chatgpt|codex)",
        rb"https?://[^\s/]+:[^\s/]+@",
    ]
    object_lines = git(root, "rev-list", "--objects", "--all").splitlines()
    scanned = 0
    for entry in object_lines:
        oid = entry.split()[0].decode()
        kind = git(root, "cat-file", "-t", oid).strip().decode()
        if kind not in {"blob", "commit"}:
            continue
        data = git(root, "cat-file", "-p", oid)
        for pattern in forbidden:
            if re.search(pattern, data):
                raise ValueError(f"Forbidden pattern in {kind} {oid}")
        scanned += 1
    commits = git(root, "log", "--all", "--format=%an <%ae>|%cn <%ce>").decode().splitlines()
    if not commits or any(line != identity + "|" + identity for line in commits):
        raise ValueError("Public author and committer must match the owner's source identity")
    if len(commits) != 1 or git(root, "show", "-s", "--format=%P", "HEAD").strip():
        raise ValueError("Public snapshot must contain only one parentless commit")
    return {
        "commits": len(commits),
        "blobs_and_commits_scanned": scanned,
        "identity": identity,
        "patterns": len(forbidden),
        "scope": "Complete reachable release history; bounded scan, not a secrets guarantee",
    }


def prepare(root, output):
    owner_name, owner_email = source_identity(root)
    candidates = git(root, "ls-files", "--cached", "--others", "--exclude-standard", "-z")
    with tempfile.TemporaryDirectory(prefix="cso-public-") as directory:
        target = Path(directory)
        for entry in candidates.decode().split("\0"):
            if (
                not entry
                or entry == "SOURCE_MANIFEST.json"
                or entry.startswith((".review/", "state/", "docs/milestones/"))
            ):
                continue
            source = root / entry
            if not source.is_file():
                continue
            destination = target / entry
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy(source, destination)
        (target / "REPORT.md").write_text(
            "# Work sample status, 2026-10-01\n\n"
            "Local verification only. See docs/RELEASE.md. No remote CI receipt or "
            "operational validation asserted.\n"
        )
        files = {
            str(p.relative_to(target)): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(target.rglob("*"))
            if p.is_file()
        }
        (target / "SOURCE_MANIFEST.json").write_text(json.dumps(files, indent=2) + "\n")
        git(target, "init", "-b", "publication-r6")
        git(target, "add", ".")
        env = dict(
            os.environ,
            GIT_AUTHOR_NAME=owner_name,
            GIT_AUTHOR_EMAIL=owner_email,
            GIT_COMMITTER_NAME=owner_name,
            GIT_COMMITTER_EMAIL=owner_email,
        )
        git(target, "commit", "-m", "Publish scoped CSO report-row work sample", env=env)
        scan = scan_history(target, f"{owner_name} <{owner_email}>")
        git(target, "fsck", "--full", "--no-reflogs")
        output.parent.mkdir(parents=True, exist_ok=True)
        git(target, "bundle", "create", str(output.resolve()), "--all")
        scan["release_commit"] = git(target, "rev-parse", "HEAD").decode().strip()
        scan["bundle_sha256"] = hashlib.sha256(output.read_bytes()).hexdigest()
        output.with_suffix(".scan.json").write_text(json.dumps(scan, indent=2) + "\n")
        print(json.dumps(scan, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    prepare(root, args.output or root / "state/public.bundle")
